#!/usr/bin/env python3
"""Build the public index.html from readable HTML components."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE_FILE = ROOT / "src" / "index.template.html"
COMPONENT_DIRECTORY = ROOT / "src" / "components"
OUTPUT_FILE = ROOT / "index.html"
SCHEDULE_FILE = ROOT / "data" / "schedule.csv"
COMPONENT_PATTERN = re.compile(r"\{\{\s*component:([a-z0-9-]+)\s*\}\}")
SCHEDULE_FALLBACK_MARKER = "{{ schedule:fallback }}"


def create_schedule_fallback() -> str:
    csv_text = SCHEDULE_FILE.read_text(encoding="utf-8")
    encoded_csv = json.dumps(csv_text, ensure_ascii=False).replace(
        "<",
        "\\u003c",
    )
    return (
        '<script type="application/json" id="schedule-fallback">'
        f"{encoded_csv}</script>"
    )


def render_site() -> str:
    template = TEMPLATE_FILE.read_text(encoding="utf-8")

    def include_component(match: re.Match[str]) -> str:
        name = match.group(1)
        component_file = COMPONENT_DIRECTORY / f"{name}.html"

        if not component_file.exists():
            raise FileNotFoundError(f"Missing component: {component_file}")

        return component_file.read_text(encoding="utf-8").strip()

    rendered = COMPONENT_PATTERN.sub(include_component, template)
    rendered = rendered.replace(
        SCHEDULE_FALLBACK_MARKER,
        create_schedule_fallback(),
    )

    if "{{" in rendered or "}}" in rendered:
        raise ValueError("An unresolved template marker remains in the output.")

    notice = (
        "<!-- Generated by tools/build.py. "
        "Edit files in src/components instead of this file. -->\n"
    )
    return rendered.replace("<!doctype html>\n", f"<!doctype html>\n{notice}", 1)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check whether index.html matches the component source.",
    )
    args = parser.parse_args()

    rendered = render_site()

    if args.check:
        current = OUTPUT_FILE.read_text(encoding="utf-8") if OUTPUT_FILE.exists() else ""
        if current != rendered:
            print("index.html is out of date. Run: python3 tools/build.py")
            return 1

        print("index.html is up to date.")
        return 0

    OUTPUT_FILE.write_text(rendered, encoding="utf-8")
    print(f"Built {OUTPUT_FILE.relative_to(ROOT)} from src/components.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
